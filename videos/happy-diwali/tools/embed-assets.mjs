// Inlines the fonts and the logo as data: URIs into js/assets-data.js.
//
// Why: browsers treat file:// images/fonts as cross-origin, which "taints" a
// canvas and blocks canvas.captureStream()/toDataURL(). Embedding the assets
// keeps index.html working when it is simply double-clicked, and keeps the
// in-browser "Export video" button working too.
//
// Usage: node tools/embed-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const b64 = (p) => readFileSync(join(root, p)).toString('base64');

const fonts = [
  { family: 'Mogra', weight: '400', file: 'assets/fonts/mogra-latin-400-normal.woff2' },
  { family: 'Galada', weight: '400', file: 'assets/fonts/galada-latin-400-normal.woff2' },
  { family: 'Baloo 2', weight: '800', file: 'assets/fonts/baloo-2-latin-800-normal.woff2' },
  { family: 'Poppins', weight: '500', file: 'assets/fonts/poppins-latin-500-normal.woff2' },
  { family: 'Poppins', weight: '600', file: 'assets/fonts/poppins-latin-600-normal.woff2' },
  { family: 'Poppins', weight: '700', file: 'assets/fonts/poppins-latin-700-normal.woff2' },
  { family: 'Poppins', weight: '800', file: 'assets/fonts/poppins-latin-800-normal.woff2' },
  { family: 'JetBrains Mono', weight: '700', file: 'assets/fonts/jetbrains-mono-latin-700-normal.woff2' },
];

const data = {
  fonts: fonts.map((f) => ({
    family: f.family,
    weight: f.weight,
    src: `url(data:font/woff2;base64,${b64(f.file)}) format("woff2")`,
  })),
  logo: `data:image/png;base64,${b64('assets/the-dev-loop-logo.png')}`,
};

const out = join(root, 'js/assets-data.js');
writeFileSync(
  out,
  '/* Generated by tools/embed-assets.mjs — do not edit by hand. */\n' +
    `window.DL_ASSETS = ${JSON.stringify(data)};\n`
);
console.log(`wrote ${out} (${(readFileSync(out).length / 1024).toFixed(0)} KB)`);
